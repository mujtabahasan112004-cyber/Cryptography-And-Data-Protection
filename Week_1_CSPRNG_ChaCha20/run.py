#!/usr/bin/env python3
"""
Command-Line Interface for Week 1:
Cryptographically Secure Pseudo-Random Number Generator (CSPRNG) Using ChaCha20.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Add project root to sys.path so src imports work cleanly
sys.path.insert(0, str(Path(__file__).parent))

from src.csprng import ChaCha20CSPRNG
from src.stats import run_statistical_tests
from src.comparison import demonstrate_rng_vulnerability


def main() -> None:
    parser = argparse.ArgumentParser(
        description="ChaCha20 Cryptographically Secure Pseudo-Random Number Generator (CSPRNG)",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python run.py --bytes 32
  python run.py --integer 1 100000
  python run.py --token 32
  python run.py --urlsafe 32
  python run.py --stats 50000
  python run.py --compare
  python run.py --demo
  python run.py --diagnostics
        """,
    )

    parser.add_argument("--bytes", type=int, metavar="N", help="Generate N secure random bytes (displayed in hex and base64)")
    parser.add_argument("--integer", nargs=2, type=int, metavar=("MIN", "MAX"), help="Generate an unbiased random integer between MIN and MAX (rejection sampled)")
    parser.add_argument("--token", type=int, metavar="N", help="Generate an N-byte secure hexadecimal token")
    parser.add_argument("--urlsafe", type=int, metavar="N", help="Generate an N-byte secure URL-safe base64 token")
    parser.add_argument("--reseed", action="store_true", help="Demonstrate explicit reseeding with fresh OS entropy")
    parser.add_argument("--stats", type=int, metavar="N", help="Run NIST statistical sanity suite on N generated bytes")
    parser.add_argument("--compare", action="store_true", help="Demonstrate vulnerability of ordinary PRNG (MT19937) vs ChaCha20")
    parser.add_argument("--diagnostics", action="store_true", help="Display CSPRNG operational state parameters and security metadata")
    parser.add_argument("--demo", action="store_true", help="Run full interactive end-to-end demonstration")

    args = parser.parse_args()

    # If no arguments provided, default to --demo
    if len(sys.argv) == 1:
        args.demo = True

    rng = ChaCha20CSPRNG()

    if args.bytes is not None:
        try:
            b = rng.random_bytes(args.bytes)
            print("=" * 60)
            print(f"ChaCha20 CSPRNG - Generated {args.bytes} Random Bytes")
            print("=" * 60)
            print(f"Hex:    {b.hex()}")
            print(f"Base64: {rng.random_urlsafe(args.bytes)}")
            print(f"Entropy Source: OS Secure Kernel (CryptGenRandom / getrandom)")
            print("=" * 60)
        except Exception as e:
            print(f"[-] Error: {e}", file=sys.stderr)
            sys.exit(1)

    if args.integer is not None:
        try:
            min_val, max_val = args.integer
            val = rng.random_int(min_val, max_val)
            print("=" * 60)
            print(f"ChaCha20 CSPRNG - Unbiased Bounded Integer")
            print("=" * 60)
            print(f"Range:    [{min_val:,}, {max_val:,}]")
            print(f"Result:   {val:,}")
            print(f"Sampling: Rejection Sampling (Zero Modulo Bias)")
            print("=" * 60)
        except Exception as e:
            print(f"[-] Error: {e}", file=sys.stderr)
            sys.exit(1)

    if args.token is not None:
        try:
            tok = rng.random_hex(args.token)
            print("=" * 60)
            print(f"ChaCha20 CSPRNG - Secure Hex Token ({args.token} bytes entropy, {len(tok)} chars)")
            print("=" * 60)
            print(f"Token: {tok}")
            print(f"Use Case: CSRF Token, API Secret, Database UUID")
            print("=" * 60)
        except Exception as e:
            print(f"[-] Error: {e}", file=sys.stderr)
            sys.exit(1)

    if args.urlsafe is not None:
        try:
            tok = rng.random_urlsafe(args.urlsafe)
            print("=" * 60)
            print(f"ChaCha20 CSPRNG - Secure URL-Safe Token ({args.urlsafe} bytes entropy)")
            print("=" * 60)
            print(f"Token: {tok}")
            print(f"Use Case: Password Reset Link, OAuth State Parameter")
            print("=" * 60)
        except Exception as e:
            print(f"[-] Error: {e}", file=sys.stderr)
            sys.exit(1)

    if args.reseed:
        print("=" * 60)
        print("ChaCha20 CSPRNG - Reseed Operation")
        print("=" * 60)
        print("Before reseed:")
        print(f"  Diagnostics: {rng.get_diagnostics()['reseed_count']} reseeds completed.")
        rng.reseed(additional_entropy=b"user_supplied_entropy_salt")
        print("After reseed with 32 fresh OS entropy bytes + additional entropy:")
        print(f"  Diagnostics: {rng.get_diagnostics()['reseed_count']} reseeds completed.")
        print(f"  Sample fresh output: {rng.random_hex(16)}")
        print("=" * 60)

    if args.diagnostics:
        diag = rng.get_diagnostics()
        print("=" * 60)
        print("ChaCha20 CSPRNG - Internal State & Security Diagnostics")
        print("=" * 60)
        for k, v in diag.items():
            print(f"  {k:30s}: {v}")
        print("=" * 60)

    if args.compare:
        print("=" * 60)
        print("SECURITY DEMONSTRATION: Mersenne Twister (MT19937) Vulnerability")
        print("=" * 60)
        res = demonstrate_rng_vulnerability()
        print(f"Tested Generator: {res['generator_tested']}")
        print(f"Samples Observed: {res['observed_samples_needed']} 32-bit words")
        print(f"Cloning Attack:   {'SUCCESSFUL - STATE RECOVERED' if res['cloning_successful'] else 'FAILED'}")
        print("\nPredicted vs Actual Future Tokens:")
        for i, (act, pred) in enumerate(zip(res["actual_future_tokens"], res["predicted_tokens"]), 1):
            print(f"  Token {i}: Target={act} | Attacker Predicts={pred} -> MATCH!")
        print("\n" + res["vulnerability_analysis"])
        print("\n" + res["csprng_solution"])
        print(f"ChaCha20 Sample Output: {res['chacha20_sample_output']}")
        print("=" * 60)

    if args.stats is not None:
        n = args.stats
        print("=" * 60)
        print(f"ChaCha20 CSPRNG - Statistical Sanity Tests ({n:,} bytes)")
        print("=" * 60)
        sample = rng.random_bytes(n)
        report = run_statistical_tests(sample)
        print(f"Shannon Entropy: {report.shannon_entropy:.6f} / {report.max_entropy:.1f} bits/byte")
        print("-" * 60)
        for t in report.results:
            status = "[PASS]" if t.passed else "[FAIL]"
            print(f"{status:8s} {t.name:<28s} (Stat: {t.statistic:.4f}, p-val: {t.p_value:.4f})")
            print(f"         {t.detail}")
        print("-" * 60)
        print(f"Overall Statistical Status: {'PASSED' if report.all_passed else 'FAILED'}")
        print("\n" + report.disclaimer)
        print("=" * 60)

    if args.demo:
        # Run the demo script
        from demo.demo_csprng import run_demonstration
        run_demonstration()


if __name__ == "__main__":
    main()
